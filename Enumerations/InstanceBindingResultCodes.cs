using System.ComponentModel.DataAnnotations;

namespace Gizmo.Web.Api.Models
{
    /// <summary>
    /// Instance binding result codes.
    /// </summary>
    public enum InstanceBindingResultCodes
    {
        /// <summary>
        /// Success.
        /// </summary>
        [Name("Success", nameof(Autogenerated.Resources.INSTANCE_BINDING_RESULT_SUCCESS_NAME))]
        [ExtendedDescription("Instance bound successfully", nameof(Autogenerated.Resources.INSTANCE_BINDING_RESULT_SUCCESS_DESCRIPTION))]
        Success = 0,

        /// <summary>
        /// Binding is not supported by the current instance authorization version.
        /// </summary>
        [Name("Not supported", nameof(Autogenerated.Resources.INSTANCE_BINDING_RESULT_NOT_SUPPORTED_NAME))]
        [ExtendedDescription("Instance binding is not supported by the current license authorization version", nameof(Autogenerated.Resources.INSTANCE_BINDING_RESULT_NOT_SUPPORTED_DESCRIPTION))]
        NotSupported = 1,

        /// <summary>
        /// The instance is not signed in or the sign in was rejected.
        /// </summary>
        [Name("Unauthorized", nameof(Autogenerated.Resources.INSTANCE_BINDING_RESULT_UNAUTHORIZED_NAME))]
        [ExtendedDescription("Sign in is required", nameof(Autogenerated.Resources.INSTANCE_BINDING_RESULT_UNAUTHORIZED_DESCRIPTION))]
        Unauthorized = 2,

        /// <summary>
        /// Network error.
        /// </summary>
        [Name("Network error", nameof(Autogenerated.Resources.INSTANCE_BINDING_RESULT_NETWORK_ERROR_NAME))]
        [ExtendedDescription("Failed due to a network error", nameof(Autogenerated.Resources.INSTANCE_BINDING_RESULT_NETWORK_ERROR_DESCRIPTION))]
        NetworkError = 3,

        /// <summary>
        /// The portal instance does not exist or belongs to another account.
        /// </summary>
        [Name("Instance not found", nameof(Autogenerated.Resources.INSTANCE_BINDING_RESULT_INSTANCE_NOT_FOUND_NAME))]
        [ExtendedDescription("The instance does not exist or belongs to another account", nameof(Autogenerated.Resources.INSTANCE_BINDING_RESULT_INSTANCE_NOT_FOUND_DESCRIPTION))]
        InstanceNotFound = 4,

        /// <summary>
        /// The portal instance is already bound to a hardware id and cannot be bound to an installation id.
        /// </summary>
        [Name("Instance unavailable", nameof(Autogenerated.Resources.INSTANCE_BINDING_RESULT_INSTANCE_UNAVAILABLE_NAME))]
        [ExtendedDescription("The instance is already bound to a hardware id and cannot be used", nameof(Autogenerated.Resources.INSTANCE_BINDING_RESULT_INSTANCE_UNAVAILABLE_DESCRIPTION))]
        InstanceUnavailable = 5,

        /// <summary>
        /// Error.
        /// </summary>
        [Name("Error", nameof(Autogenerated.Resources.INSTANCE_BINDING_RESULT_ERROR_NAME))]
        [ExtendedDescription("Failed due to an error", nameof(Autogenerated.Resources.INSTANCE_BINDING_RESULT_ERROR_DESCRIPTION))]
        Error = 6,
    }
}
